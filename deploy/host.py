"""Create a Tally host on Vultr, send it releases, and read its status page.

    python deploy/host.py create [--region ewr]    a VX1 instance whose first boot installs and checks this commit
    python deploy/host.py push                     send this commit as a release
    python deploy/host.py status                   print the host's /status.txt

Needs VULTR_API_KEY (create only) and TALLY_DEPLOY_TOKEN; push and status need TALLY_HOST (printed by create).
A release is `git archive HEAD`: committed files only. The host gets the SHA-256 of the deploy token, never the
token, and the root password Vultr returns is never printed.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import subprocess
import sys
import textwrap
import time
import urllib.request
from pathlib import Path

API = "https://api.vultr.com/v2"
PLAN = "vx1-g-2c-8g-120s"   # VX1: 2 vCPU, 8 GB, 120 GB, with KVM inside, which Microsandbox needs
UBUNTU_24_04 = 2284
ROOT = Path(__file__).resolve().parent.parent


def _env(name: str) -> str:
    value = os.environ.get(name, "")
    if not value:
        sys.exit(f"{name} is not set")
    return value


def _vultr(method: str, path: str, body: dict | None = None) -> dict:
    req = urllib.request.Request(API + path, method=method, data=json.dumps(body).encode() if body else None,
                                 headers={"Authorization": f"Bearer {_env('VULTR_API_KEY')}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read() or b"{}")


def _release() -> tuple[str, bytes]:
    if subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=ROOT, capture_output=True, text=True).stdout.strip():
        print("note: uncommitted changes are not part of the release", file=sys.stderr)
    revision = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    tarball = subprocess.run(["git", "archive", "--format=tar.gz", "HEAD"], cwd=ROOT, capture_output=True, check=True).stdout
    return revision, tarball


def first_boot(revision: str, tarball: bytes, token_sha256: str) -> str:
    release = f"/opt/tally/releases/{time.strftime('%Y%m%d-%H%M%S', time.gmtime())}-{revision[:12]}"
    code = "\n".join(textwrap.wrap(base64.b64encode(tarball).decode(), 76))
    return f"""#!/bin/bash
# Tally host, first boot. Generated by deploy/host.py for commit {revision}.
set -uo pipefail
exec >>/var/log/tally-first-boot.log 2>&1
install -d -m 0755 /etc/tally /opt/tally /opt/tally/releases
echo {token_sha256} > /etc/tally/deploy-token.sha256
mkdir -p {release}
base64 -d <<'CODE' | tar -xz -C {release}
{code}
CODE
echo {revision} > {release}/REVISION
bash {release}/deploy/host-setup.sh {release}
"""


def create(region: str) -> None:
    revision, tarball = _release()
    script = first_boot(revision, tarball, hashlib.sha256(_env("TALLY_DEPLOY_TOKEN").encode()).hexdigest())
    made = _vultr("POST", "/instances", {
        "region": region, "plan": PLAN, "os_id": UBUNTU_24_04, "label": "tally-1", "hostname": "tally-1",
        "tags": ["tally"], "backups": "disabled", "enable_ipv6": False, "activation_email": False,
        "user_data": base64.b64encode(script.encode()).decode(),
    })["instance"]
    instance_id = made["id"]
    print(json.dumps({"instance_id": instance_id, "revision": revision}), flush=True)
    for _ in range(60):  # the address is assigned a little after the instance is created
        ip = _vultr("GET", f"/instances/{instance_id}")["instance"]["main_ip"]
        if ip and ip != "0.0.0.0":
            print(json.dumps({"instance_id": instance_id, "ip": ip, "host": ip.replace(".", "-") + ".sslip.io"}))
            return
        time.sleep(10)
    sys.exit("no address yet; check the instance in the Vultr console")


def push() -> None:
    revision, tarball = _release()
    req = urllib.request.Request(f"https://{_env('TALLY_HOST')}/deploy", method="POST", data=tarball, headers={
        "Authorization": f"Bearer {_env('TALLY_DEPLOY_TOKEN')}", "X-Tally-Revision": revision,
        "Content-Type": "application/gzip"})
    with urllib.request.urlopen(req, timeout=120) as r:
        print(r.status, r.read().decode().strip())


def status() -> None:
    with urllib.request.urlopen(f"https://{_env('TALLY_HOST')}/status.txt", timeout=60) as r:
        print(r.read().decode())


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["create", "push", "status"])
    ap.add_argument("--region", default="ewr")
    a = ap.parse_args()
    {"create": lambda: create(a.region), "push": push, "status": status}[a.command]()
